CREATE TABLE user_llm_credential (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES app_user(id) ON DELETE CASCADE,
    ciphertext BYTEA NOT NULL,
    iv BYTEA NOT NULL,
    algorithm_version SMALLINT NOT NULL,
    key_version SMALLINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_user_llm_credential_iv_length CHECK (octet_length(iv) = 12),
    CONSTRAINT ck_user_llm_credential_ciphertext_length CHECK (octet_length(ciphertext) >= 16),
    CONSTRAINT ck_user_llm_credential_versions_positive CHECK (algorithm_version > 0 AND key_version > 0)
);
