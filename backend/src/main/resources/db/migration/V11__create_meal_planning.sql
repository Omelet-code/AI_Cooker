-- 餐单使用独立版本资源，不写旧轮次或伪造助手消息；归属和并发由关系约束兜底。
CREATE TABLE meal_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    profile_dining_count INTEGER CHECK (profile_dining_count IS NULL OR profile_dining_count > 0),
    dining_count INTEGER CHECK (dining_count IS NULL OR dining_count > 0),
    dining_count_source VARCHAR(16) CHECK (dining_count_source IN ('EXPLICIT','PROFILE')),
    current_version INTEGER NOT NULL DEFAULT 1 CHECK (current_version > 0),
    status VARCHAR(24) NOT NULL CHECK (status IN ('PENDING','CLARIFICATION','OPTIONS_READY','SELECTED','FAILED')),
    selected_option_id BIGINT,
    view_json JSONB NOT NULL CHECK (jsonb_typeof(view_json) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (id,conversation_id,user_id),
    CONSTRAINT fk_meal_conversation_owner FOREIGN KEY (conversation_id,user_id) REFERENCES conversation(id,user_id) ON DELETE CASCADE
);
CREATE TABLE meal_action (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_id BIGINT NOT NULL,
    conversation_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    version INTEGER NOT NULL CHECK (version > 0),
    request_id UUID NOT NULL,
    type VARCHAR(8) NOT NULL CHECK (type IN ('CREATE','REVISE','SELECT')),
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING','RUNNING','SUCCEEDED','FAILED')),
    input_text TEXT NOT NULL,
    parameters JSONB NOT NULL CHECK (jsonb_typeof(parameters) = 'object'),
    input_hash CHAR(64) NOT NULL,
    seed BIGINT,
    deadline_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    result JSONB CHECK (result IS NULL OR (jsonb_typeof(result) = 'object' AND octet_length(result::text) <= 524288)),
    metrics JSONB NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(metrics) = 'object'),
    error_code VARCHAR(64),
    UNIQUE (user_id,conversation_id,request_id),
    CONSTRAINT fk_meal_action_owner FOREIGN KEY (meal_id,conversation_id,user_id) REFERENCES meal_session(id,conversation_id,user_id) ON DELETE CASCADE,
    CHECK ((status='PENDING' AND started_at IS NULL AND finished_at IS NULL AND error_code IS NULL)
        OR (status='RUNNING' AND started_at IS NOT NULL AND finished_at IS NULL AND error_code IS NULL)
        OR (status='SUCCEEDED' AND started_at IS NOT NULL AND finished_at IS NOT NULL AND error_code IS NULL)
        OR (status='FAILED' AND finished_at IS NOT NULL AND error_code IS NOT NULL))
);
CREATE UNIQUE INDEX uq_meal_active_action ON meal_action(meal_id) WHERE status IN ('PENDING','RUNNING');
CREATE INDEX ix_meal_list ON meal_session(user_id,conversation_id,updated_at DESC,id DESC);
CREATE TABLE meal_option (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_id BIGINT NOT NULL,
    conversation_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    version INTEGER NOT NULL CHECK (version > 0),
    ordinal INTEGER NOT NULL CHECK (ordinal IN (1,2)),
    schema_version INTEGER NOT NULL DEFAULT 1 CHECK (schema_version = 1),
    facts JSONB NOT NULL CHECK (jsonb_typeof(facts) = 'object' AND octet_length(facts::text) <= 262144),
    UNIQUE (meal_id,version,ordinal),
    UNIQUE (id,meal_id,version,conversation_id,user_id),
    CONSTRAINT fk_meal_option_owner FOREIGN KEY (meal_id,conversation_id,user_id) REFERENCES meal_session(id,conversation_id,user_id) ON DELETE CASCADE
);
-- 选项必须属于本餐当前版本；修订先清除选定，禁止旧版本或其他用户选项穿透。
ALTER TABLE meal_session ADD CONSTRAINT fk_meal_selected_option_owner
    FOREIGN KEY (selected_option_id,id,current_version,conversation_id,user_id)
    REFERENCES meal_option(id,meal_id,version,conversation_id,user_id);
