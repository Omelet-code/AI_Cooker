CREATE TABLE recipe_import_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_type VARCHAR(32) NOT NULL,
    source_version VARCHAR(128) NOT NULL,
    status VARCHAR(32) NOT NULL,
    candidate_count INTEGER NOT NULL DEFAULT 0,
    succeeded_count INTEGER NOT NULL DEFAULT 0,
    skipped_count INTEGER NOT NULL DEFAULT 0,
    warning_count INTEGER NOT NULL DEFAULT 0,
    failed_count INTEGER NOT NULL DEFAULT 0,
    error_summary JSONB,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ
);

CREATE TABLE recipe_source (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_type VARCHAR(32) NOT NULL,
    source_key VARCHAR(1024) NOT NULL,
    source_uri TEXT,
    owner_user_id BIGINT,
    visibility VARCHAR(32) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_recipe_source_type CHECK (source_type IN ('SYSTEM_HOWTOCOOK', 'USER_CUSTOM')),
    CONSTRAINT ck_recipe_source_visibility CHECK (visibility IN ('PUBLIC', 'PRIVATE')),
    CONSTRAINT ck_recipe_source_owner CHECK (
        (source_type = 'SYSTEM_HOWTOCOOK' AND owner_user_id IS NULL AND visibility = 'PUBLIC')
        OR (source_type = 'USER_CUSTOM' AND owner_user_id IS NOT NULL AND visibility = 'PRIVATE')
    )
);
CREATE UNIQUE INDEX uq_recipe_source_system_key
    ON recipe_source (source_type, source_key) WHERE owner_user_id IS NULL;
CREATE UNIQUE INDEX uq_recipe_source_user_key
    ON recipe_source (owner_user_id, source_key) WHERE source_type = 'USER_CUSTOM';

CREATE TABLE recipe_source_document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL REFERENCES recipe_source(id),
    source_version VARCHAR(128) NOT NULL,
    content_hash CHAR(64) NOT NULL,
    raw_markdown TEXT NOT NULL,
    parse_status VARCHAR(32) NOT NULL,
    parse_warnings JSONB NOT NULL DEFAULT '[]'::jsonb,
    failure_message TEXT,
    import_batch_id BIGINT REFERENCES recipe_import_batch(id),
    imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_recipe_source_document_status CHECK (parse_status IN ('SUCCESS', 'FAILED')),
    CONSTRAINT uq_recipe_source_document_version UNIQUE (source_id, source_version)
);

CREATE TABLE recipe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL UNIQUE REFERENCES recipe_source(id),
    source_document_id BIGINT NOT NULL REFERENCES recipe_source_document(id),
    name VARCHAR(255) NOT NULL,
    category_code VARCHAR(128) NOT NULL,
    summary TEXT,
    difficulty INTEGER,
    estimated_minutes INTEGER,
    servings INTEGER,
    calories_kcal INTEGER,
    additional_content TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_recipe_difficulty CHECK (difficulty IS NULL OR difficulty BETWEEN 1 AND 5),
    CONSTRAINT ck_recipe_minutes CHECK (estimated_minutes IS NULL OR estimated_minutes >= 0),
    CONSTRAINT ck_recipe_servings CHECK (servings IS NULL OR servings > 0),
    CONSTRAINT ck_recipe_calories CHECK (calories_kcal IS NULL OR calories_kcal >= 0)
);
CREATE INDEX ix_recipe_name ON recipe(name);

CREATE TABLE ingredient (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_name VARCHAR(255) NOT NULL UNIQUE,
    normalization_status VARCHAR(32) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_ingredient_normalization_status CHECK (normalization_status IN ('UNREVIEWED', 'REVIEWED'))
);

CREATE TABLE ingredient_alias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_id BIGINT NOT NULL REFERENCES ingredient(id),
    alias_name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE recipe_ingredient (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id BIGINT NOT NULL REFERENCES recipe(id) ON DELETE CASCADE,
    ingredient_id BIGINT REFERENCES ingredient(id),
    raw_name VARCHAR(255) NOT NULL,
    amount_min NUMERIC,
    amount_max NUMERIC,
    unit_code VARCHAR(16),
    unit_label VARCHAR(64),
    optional BOOLEAN NOT NULL DEFAULT FALSE,
    raw_line TEXT NOT NULL,
    sort_order INTEGER NOT NULL,
    CONSTRAINT ck_recipe_ingredient_amount CHECK (amount_min IS NULL OR amount_max IS NULL OR amount_min <= amount_max),
    CONSTRAINT uq_recipe_ingredient_order UNIQUE (recipe_id, sort_order)
);

CREATE TABLE cooking_tool (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE recipe_tool (
    recipe_id BIGINT NOT NULL REFERENCES recipe(id) ON DELETE CASCADE,
    tool_id BIGINT NOT NULL REFERENCES cooking_tool(id),
    optional BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (recipe_id, tool_id)
);

CREATE TABLE recipe_step (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id BIGINT NOT NULL REFERENCES recipe(id) ON DELETE CASCADE,
    step_no INTEGER NOT NULL,
    content TEXT NOT NULL,
    CONSTRAINT ck_recipe_step_no CHECK (step_no > 0),
    CONSTRAINT uq_recipe_step_order UNIQUE (recipe_id, step_no)
);
