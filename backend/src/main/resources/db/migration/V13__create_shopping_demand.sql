-- 清单独立快照；核心归属/状态/数量为关系列，证据保留完整原精度与未知。
CREATE TABLE shopping_list (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    conversation_id BIGINT NOT NULL,
    meal_id BIGINT NOT NULL,
    version INTEGER NOT NULL CHECK(version>0),
    option_id BIGINT NOT NULL,
    request_id UUID NOT NULL,
    input_hash CHAR(64) NOT NULL CHECK(input_hash ~ '^[0-9a-f]{64}$'),
    source_fingerprint CHAR(64) NOT NULL CHECK(source_fingerprint ~ '^[0-9a-f]{64}$'),
    status VARCHAR(24) NOT NULL CHECK(status IN ('DRAFT','READY_FOR_MATCHING')),
    matching_status VARCHAR(16) NOT NULL DEFAULT 'NOT_MATCHED' CHECK(matching_status='NOT_MATCHED'),
    budget_yuan NUMERIC(18,2) CHECK(budget_yuan IS NULL OR (budget_yuan>=0 AND budget_yuan <> 'NaN'::numeric)),
    budget_status VARCHAR(24) NOT NULL CHECK(budget_status IN ('NOT_SET','UNKNOWN','WITHIN_BUDGET','OVER_BUDGET')),
    estimated_demand_cost NUMERIC(18,2) CHECK(estimated_demand_cost IS NULL OR (estimated_demand_cost>=0 AND estimated_demand_cost <> 'NaN'::numeric)),
    consumption_cost NUMERIC(18,2) CHECK(consumption_cost IS NULL OR (consumption_cost>=0 AND consumption_cost <> 'NaN'::numeric)),
    purchase_outlay NUMERIC(18,2) CHECK(purchase_outlay IS NULL OR (purchase_outlay>=0 AND purchase_outlay <> 'NaN'::numeric)),
    known_subtotal NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK(known_subtotal>=0 AND known_subtotal <> 'NaN'::numeric),
    unknown_item_count INTEGER NOT NULL CHECK(unknown_item_count>=0),
    evidence_json JSONB NOT NULL CHECK(jsonb_typeof(evidence_json)='object' AND octet_length(evidence_json::text)<=1048576),
    view_json JSONB NOT NULL CHECK(jsonb_typeof(view_json)='object' AND octet_length(view_json::text)<=1048576),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE(user_id,request_id),
    UNIQUE(id,user_id),
    CONSTRAINT fk_shopping_option_owner FOREIGN KEY(option_id,meal_id,version,conversation_id,user_id)
        REFERENCES meal_option(id,meal_id,version,conversation_id,user_id) ON DELETE CASCADE
);
CREATE INDEX ix_shopping_user_created ON shopping_list(user_id,created_at DESC,id DESC);
CREATE TABLE shopping_list_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    list_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    line_order INTEGER NOT NULL CHECK(line_order>0),
    item_key VARCHAR(64) NOT NULL,
    ingredient_id BIGINT,
    unit_code VARCHAR(32),
    unit_label VARCHAR(64),
    optional BOOLEAN NOT NULL,
    required_amount NUMERIC(24,8) CHECK(required_amount IS NULL OR (required_amount>=0 AND required_amount <> 'NaN'::numeric)),
    shortage_amount NUMERIC(24,8) CHECK(shortage_amount IS NULL OR (shortage_amount>=0 AND shortage_amount <> 'NaN'::numeric)),
    status VARCHAR(24) NOT NULL CHECK(status IN ('HAVE_ENOUGH','NEED_BUY','QUANTITY_PENDING')),
    CHECK((status='HAVE_ENOUGH' AND shortage_amount IS NOT NULL AND shortage_amount=0)
        OR (status='NEED_BUY' AND required_amount IS NOT NULL AND shortage_amount IS NOT NULL AND required_amount>0 AND shortage_amount=required_amount AND unit_code IS NOT NULL)
        OR (status='QUANTITY_PENDING' AND required_amount IS NULL AND shortage_amount IS NULL)),
    UNIQUE(list_id,line_order),
    UNIQUE(list_id,item_key),
    CONSTRAINT fk_shopping_item_owner FOREIGN KEY(list_id,user_id) REFERENCES shopping_list(id,user_id) ON DELETE CASCADE
);
