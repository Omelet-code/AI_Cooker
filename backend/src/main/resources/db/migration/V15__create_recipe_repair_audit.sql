-- D1-B显式治理审计；迁移不触发事实修复，验证仅使用临时PG。
CREATE TABLE recipe_repair_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key UUID NOT NULL UNIQUE,
    input_hash CHAR(64) NOT NULL CHECK (input_hash ~ '^[0-9A-F]{64}$'),
    manifest_hash CHAR(64) NOT NULL CHECK (manifest_hash ~ '^[0-9A-F]{64}$'),
    approval_hash CHAR(64) NOT NULL CHECK (approval_hash ~ '^[0-9A-F]{64}$'),
    rule_version VARCHAR(64) NOT NULL,
    target_database VARCHAR(128) NOT NULL,
    target_identifier VARCHAR(1024) NOT NULL,
    reviewer VARCHAR(255) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('APPLIED','ROLLED_BACK')),
    state_json JSONB NOT NULL CHECK (jsonb_typeof(state_json)='object'),
    result_json JSONB NOT NULL CHECK (jsonb_typeof(result_json)='object'),
    applied_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    rolled_back_at TIMESTAMPTZ
);
CREATE TABLE recipe_repair_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES recipe_repair_batch(id),
    candidate_key VARCHAR(255) NOT NULL,
    source_id BIGINT,
    recipe_id BIGINT,
    original_line_id BIGINT,
    resulting_line_id BIGINT,
    action VARCHAR(24) NOT NULL,
    before_json JSONB,
    after_json JSONB,
    execution_json JSONB NOT NULL CHECK (jsonb_typeof(execution_json)='object'),
    UNIQUE(batch_id,candidate_key)
);
CREATE INDEX ix_recipe_repair_entry_recipe ON recipe_repair_entry(recipe_id,batch_id);
