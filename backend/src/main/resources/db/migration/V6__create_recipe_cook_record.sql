CREATE TABLE recipe_cook_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    recipe_id BIGINT NOT NULL REFERENCES recipe(id) ON DELETE RESTRICT,
    idempotency_key UUID NOT NULL,
    rating SMALLINT,
    cooked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_recipe_cook_record_user_key UNIQUE (user_id, idempotency_key),
    CONSTRAINT ck_recipe_cook_record_rating CHECK (rating BETWEEN 1 AND 5)
);

CREATE INDEX ix_recipe_cook_record_user_recipe_time
    ON recipe_cook_record (user_id, recipe_id, cooked_at DESC, id DESC);
