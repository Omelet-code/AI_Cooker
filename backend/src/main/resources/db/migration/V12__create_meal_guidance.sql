-- 指导共用餐单动作执行位；不修改旧迁移或增加第二套活动状态。
ALTER TABLE meal_action DROP CONSTRAINT meal_action_type_check;
ALTER TABLE meal_action ADD CONSTRAINT meal_action_type_check CHECK (type IN ('CREATE','REVISE','SELECT','GUIDE'));
ALTER TABLE meal_action ADD CONSTRAINT uq_meal_action_guide_owner UNIQUE(id,meal_id,version,conversation_id,user_id);
CREATE TABLE meal_guide (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    conversation_id BIGINT NOT NULL,
    meal_id BIGINT NOT NULL,
    version INTEGER NOT NULL CHECK(version > 0),
    option_id BIGINT NOT NULL,
    action_id BIGINT NOT NULL UNIQUE,
    schema_version INTEGER NOT NULL DEFAULT 1 CHECK(schema_version=1),
    persona_version VARCHAR(32) NOT NULL,
    prompt_version VARCHAR(32) NOT NULL,
    view_json JSONB NOT NULL CHECK(jsonb_typeof(view_json)='object' AND octet_length(view_json::text)<=524288),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE(meal_id,version,option_id),
    CONSTRAINT fk_guide_meal_owner FOREIGN KEY(meal_id,conversation_id,user_id) REFERENCES meal_session(id,conversation_id,user_id) ON DELETE CASCADE,
    CONSTRAINT fk_guide_option_owner FOREIGN KEY(option_id,meal_id,version,conversation_id,user_id) REFERENCES meal_option(id,meal_id,version,conversation_id,user_id) ON DELETE CASCADE,
    CONSTRAINT fk_guide_action_owner FOREIGN KEY(action_id,meal_id,version,conversation_id,user_id) REFERENCES meal_action(id,meal_id,version,conversation_id,user_id) ON DELETE CASCADE
);
