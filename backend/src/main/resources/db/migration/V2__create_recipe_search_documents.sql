CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS zhparser;

CREATE TEXT SEARCH CONFIGURATION cooker_zh (PARSER = zhparser);
ALTER TEXT SEARCH CONFIGURATION cooker_zh ADD MAPPING FOR n, v, a, i, e, l WITH simple;

CREATE TABLE recipe_search_document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id BIGINT NOT NULL REFERENCES recipe(id) ON DELETE CASCADE,
    source_document_id BIGINT NOT NULL REFERENCES recipe_source_document(id),
    source_type VARCHAR(32) NOT NULL,
    owner_user_id BIGINT,
    visibility VARCHAR(32) NOT NULL,
    chunk_type VARCHAR(32) NOT NULL,
    chunk_no INTEGER NOT NULL,
    content TEXT NOT NULL,
    tsv TSVECTOR GENERATED ALWAYS AS (to_tsvector('cooker_zh'::regconfig, content)) STORED,
    content_hash CHAR(64) NOT NULL,
    document_template_version INTEGER NOT NULL,
    embedding_model VARCHAR(128) NOT NULL,
    embedding_dimension INTEGER NOT NULL,
    embedding VECTOR(1024),
    embedding_status VARCHAR(32) NOT NULL,
    failure_message TEXT,
    indexed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_recipe_search_document_chunk_type
        CHECK (chunk_type IN ('overview', 'ingredients', 'steps', 'tools')),
    CONSTRAINT ck_recipe_search_document_chunk_no CHECK (chunk_no >= 0),
    CONSTRAINT ck_recipe_search_document_visibility CHECK (visibility IN ('PUBLIC', 'PRIVATE')),
    CONSTRAINT ck_recipe_search_document_status CHECK (embedding_status IN ('PENDING', 'READY', 'FAILED')),
    CONSTRAINT ck_recipe_search_document_dimension CHECK (embedding_dimension = 1024),
    CONSTRAINT uq_recipe_search_document_chunk UNIQUE (recipe_id, chunk_type, chunk_no)
);

CREATE INDEX ix_recipe_search_document_ready_version
    ON recipe_search_document (embedding_status, embedding_model, embedding_dimension, document_template_version);
CREATE INDEX ix_recipe_search_document_recipe_id ON recipe_search_document (recipe_id);
CREATE INDEX ix_recipe_search_document_tsv ON recipe_search_document USING GIN (tsv);
