-- 商品匹配独立保存，T16需求/确认/预算快照不更新。
CREATE TABLE shopping_product_match (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    list_id BIGINT NOT NULL,
    request_id UUID NOT NULL,
    input_hash CHAR(64) NOT NULL CHECK(input_hash ~ '^[0-9a-f]{64}$'),
    source_fingerprint CHAR(64) NOT NULL CHECK(source_fingerprint ~ '^[0-9a-f]{64}$'),
    city_code CHAR(6) NOT NULL CHECK(city_code ~ '^[0-9]{6}$'),
    provider VARCHAR(16) NOT NULL DEFAULT 'MOCK' CHECK(provider='MOCK'),
    real_data BOOLEAN NOT NULL DEFAULT false CHECK(real_data=false),
    catalog_version VARCHAR(64) NOT NULL,
    captured_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    matching_status VARCHAR(16) NOT NULL CHECK(matching_status IN ('NOT_NEEDED','MATCHED','PARTIAL','NO_MATCH')),
    estimated_demand_cost NUMERIC(18,2) CHECK(estimated_demand_cost IS NULL OR (estimated_demand_cost>=0 AND estimated_demand_cost <> 'NaN'::numeric)),
    consumption_cost NUMERIC(18,2) CHECK(consumption_cost IS NULL OR (consumption_cost>=0 AND consumption_cost <> 'NaN'::numeric)),
    purchase_outlay NUMERIC(18,2) CHECK(purchase_outlay IS NULL OR (purchase_outlay>=0 AND purchase_outlay <> 'NaN'::numeric)),
    known_subtotal NUMERIC(18,2) NOT NULL CHECK(known_subtotal>=0 AND known_subtotal <> 'NaN'::numeric),
    unknown_item_count INTEGER NOT NULL CHECK(unknown_item_count>=0),
    estimated_known_subtotal NUMERIC(18,2) NOT NULL CHECK(estimated_known_subtotal>=0 AND estimated_known_subtotal <> 'NaN'::numeric),
    estimated_unknown_item_count INTEGER NOT NULL CHECK(estimated_unknown_item_count>=0),
    budget_status VARCHAR(24) NOT NULL CHECK(budget_status IN ('NOT_SET','UNKNOWN','WITHIN_BUDGET','OVER_BUDGET')),
    view_json JSONB NOT NULL CHECK(jsonb_typeof(view_json)='object' AND octet_length(view_json::text)<=1048576),
    UNIQUE(user_id,request_id),
    UNIQUE(id,list_id,user_id),
    CONSTRAINT fk_product_match_list_owner FOREIGN KEY(list_id,user_id) REFERENCES shopping_list(id,user_id) ON DELETE CASCADE
);
CREATE INDEX ix_product_match_latest ON shopping_product_match(user_id,list_id,id DESC);
CREATE TABLE shopping_product_match_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL,
    list_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    line_order INTEGER NOT NULL CHECK(line_order>0),
    item_key VARCHAR(64) NOT NULL,
    ingredient_id BIGINT,
    unit_code VARCHAR(32),
    required_amount NUMERIC(24,8) CHECK(required_amount IS NULL OR (required_amount>=0 AND required_amount <> 'NaN'::numeric)),
    shortage_amount NUMERIC(24,8) CHECK(shortage_amount IS NULL OR (shortage_amount>=0 AND shortage_amount <> 'NaN'::numeric)),
    status VARCHAR(24) NOT NULL CHECK(status IN ('HAVE_ENOUGH','MATCHED','QUANTITY_PENDING','UNIT_UNSUPPORTED','NO_PRODUCT','OUT_OF_STOCK','QUOTE_UNKNOWN')),
    product_id VARCHAR(64),
    package_amount NUMERIC(24,8) CHECK(package_amount IS NULL OR (package_amount>0 AND package_amount <> 'NaN'::numeric)),
    package_unit VARCHAR(32),
    package_price NUMERIC(18,2) CHECK(package_price IS NULL OR (package_price>=0 AND package_price <> 'NaN'::numeric)),
    package_count NUMERIC(24,8) CHECK(package_count IS NULL OR (package_count>=0 AND package_count=trunc(package_count) AND package_count <> 'NaN'::numeric)),
    consumption_cost NUMERIC(18,2) CHECK(consumption_cost IS NULL OR (consumption_cost>=0 AND consumption_cost <> 'NaN'::numeric)),
    purchase_outlay NUMERIC(18,2) CHECK(purchase_outlay IS NULL OR (purchase_outlay>=0 AND purchase_outlay <> 'NaN'::numeric)),
    estimated_demand_cost NUMERIC(18,2) CHECK(estimated_demand_cost IS NULL OR (estimated_demand_cost>=0 AND estimated_demand_cost <> 'NaN'::numeric)),
    quote_json JSONB CHECK(quote_json IS NULL OR jsonb_typeof(quote_json)='object'),
    CHECK(status<>'MATCHED' OR (product_id IS NOT NULL AND required_amount IS NOT NULL AND shortage_amount IS NOT NULL AND shortage_amount>0 AND package_amount IS NOT NULL AND package_unit IS NOT NULL AND package_price IS NOT NULL AND package_count IS NOT NULL AND package_count>=1 AND consumption_cost IS NOT NULL AND purchase_outlay IS NOT NULL)),
    UNIQUE(match_id,item_key),
    UNIQUE(match_id,line_order),
    CONSTRAINT fk_product_match_item_owner FOREIGN KEY(match_id,list_id,user_id) REFERENCES shopping_product_match(id,list_id,user_id) ON DELETE CASCADE
);
CREATE TABLE shopping_product_purchase_group (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL,
    list_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    group_key VARCHAR(160) NOT NULL,
    product_id VARCHAR(64) NOT NULL,
    unit_code VARCHAR(32) NOT NULL,
    quantity NUMERIC(24,8) NOT NULL CHECK(quantity>0 AND quantity <> 'NaN'::numeric),
    package_count NUMERIC(24,8) NOT NULL CHECK(package_count>=1 AND package_count=trunc(package_count) AND package_count <> 'NaN'::numeric),
    purchase_outlay NUMERIC(18,2) NOT NULL CHECK(purchase_outlay>=0 AND purchase_outlay <> 'NaN'::numeric),
    UNIQUE(match_id,group_key),
    CONSTRAINT fk_product_purchase_group_owner FOREIGN KEY(match_id,list_id,user_id) REFERENCES shopping_product_match(id,list_id,user_id) ON DELETE CASCADE
);
