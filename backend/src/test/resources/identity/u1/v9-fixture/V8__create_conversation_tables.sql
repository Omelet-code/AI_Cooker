CREATE TABLE conversation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    title VARCHAR(100) NOT NULL,
    next_turn_no BIGINT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT uq_conversation_id_user UNIQUE (id, user_id),
    CONSTRAINT ck_conversation_title_nonblank CHECK (length(btrim(title)) > 0),
    CONSTRAINT ck_conversation_next_turn_no_positive CHECK (next_turn_no > 0)
);

CREATE INDEX ix_conversation_user_updated ON conversation (user_id, updated_at DESC, id DESC);

CREATE TABLE conversation_turn (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    request_id UUID NOT NULL,
    input_hash CHAR(64) NOT NULL,
    turn_no BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    deadline_at TIMESTAMPTZ NOT NULL,
    error_code VARCHAR(64),
    CONSTRAINT fk_turn_conversation_owner FOREIGN KEY (conversation_id, user_id)
        REFERENCES conversation (id, user_id) ON DELETE CASCADE,
    CONSTRAINT uq_turn_request UNIQUE (user_id, conversation_id, request_id),
    CONSTRAINT uq_turn_number UNIQUE (conversation_id, turn_no),
    CONSTRAINT uq_turn_id_owner UNIQUE (id, conversation_id, user_id),
    CONSTRAINT ck_turn_input_hash CHECK (input_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_turn_no_positive CHECK (turn_no > 0),
    CONSTRAINT ck_turn_status CHECK (
        (status = 'PENDING' AND started_at IS NULL AND finished_at IS NULL AND error_code IS NULL) OR
        (status = 'RUNNING' AND started_at IS NOT NULL AND finished_at IS NULL AND error_code IS NULL) OR
        (status = 'SUCCEEDED' AND started_at IS NOT NULL AND finished_at IS NOT NULL AND error_code IS NULL) OR
        (status = 'FAILED' AND finished_at IS NOT NULL AND error_code IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uq_turn_one_active_per_conversation
    ON conversation_turn (conversation_id) WHERE status IN ('PENDING', 'RUNNING');
CREATE INDEX ix_turn_expiry ON conversation_turn (conversation_id, deadline_at)
    WHERE status IN ('PENDING', 'RUNNING');

CREATE TABLE chat_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    turn_id BIGINT NOT NULL,
    role VARCHAR(16) NOT NULL,
    content TEXT NOT NULL,
    sequence BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT fk_message_turn_owner FOREIGN KEY (turn_id, conversation_id, user_id)
        REFERENCES conversation_turn (id, conversation_id, user_id) ON DELETE CASCADE,
    CONSTRAINT uq_message_conversation_sequence UNIQUE (conversation_id, sequence),
    CONSTRAINT uq_message_turn_role UNIQUE (turn_id, role),
    CONSTRAINT ck_message_role CHECK (role IN ('USER', 'ASSISTANT')),
    CONSTRAINT ck_message_sequence_positive CHECK (sequence > 0),
    CONSTRAINT ck_message_content_nonblank CHECK (length(btrim(content)) > 0)
);

CREATE INDEX ix_message_history ON chat_message (conversation_id, sequence, id);
